#!/bin/bash
# gen_linker_tables.sh - generate the ELF relocation reference block that is
# compiled into tools/linker.c.
#
# The block is real ABI data: it is produced from the LLVM ELF relocation
# definition files and is printed by `linker --list-relocs[=all]`.
#
# Usage:
#   tools/gen_linker_tables.sh [defdir] [output]
# If output is omitted the block is written to stdout.
set -e
DEFDIR="${1:-/data/data/com.termux/files/usr/include/llvm/BinaryFormat/ELFRelocs}"
OUT="${2:-}"
ARCH_FILES="AArch64 ARM RISCV x86_64 i386 PowerPC PowerPC64 Mips LoongArch Hexagon Sparc SystemZ CSKY ARC Xtensa M68k AVR VE AMDGPU MSP430 Lanai BPF"

emit() {
  echo "/* ------------------------------------------------------------------------- */"
  echo "/* ELF relocation reference table (generated by tools/gen_linker_tables.sh).  */"
  echo "/* Used by the --list-relocs diagnostic; the linker itself implements the     */"
  echo "/* AArch64 subset.                                                           */"
  echo "/* ------------------------------------------------------------------------- */"
  echo "typedef struct { const char *arch; unsigned value; const char *name; const char *doc; } WallRelocRef;"
  echo "static const WallRelocRef g_reloc_ref[] = {"
  for a in $ARCH_FILES; do
    f="$DEFDIR/$a.def"
    [ -f "$f" ] || continue
    arch=$(echo "$a" | tr 'A-Z' 'a-z')
    awk -v a="$arch" '
      /^ELF_RELOC\(/ {
        line = $0
        sub(/^ELF_RELOC\(/, "", line)
        sub(/\).*/, "", line)
        n = split(line, p, ",")
        name = p[1]; gsub(/[ \t]/, "", name)
        val  = p[2]; gsub(/[ \t]/, "", val)
        short = name
        sub(/^R_[A-Z0-9]+_/, "", short)
        if (short == "") short = name
        printf("  {\"%s\", %s, \"%s\", \"%s relocation (%s).\"},\n", a, val, name, short, a)
      }' "$f"
  done
  echo "};"
  echo "static const int g_reloc_ref_count = (int)(sizeof(g_reloc_ref) / sizeof(g_reloc_ref[0]));"
  echo ""
  echo "static void wall_list_relocs(int all) {"
  echo "  int shown = 0;"
  echo "  for (int i = 0; i < g_reloc_ref_count; i++) {"
  echo "    if (!all && strcmp(g_reloc_ref[i].arch, \"aarch64\") != 0) continue;"
  echo "    printf(\"%-10s 0x%04x  %-44s %s\\n\", g_reloc_ref[i].arch,"
  echo "           g_reloc_ref[i].value, g_reloc_ref[i].name, g_reloc_ref[i].doc);"
  echo "    shown++;"
  echo "  }"
  echo "  fprintf(stderr, \"linker: %d relocation names listed\\n\", shown);"
  echo "}"
}

if [ -n "$OUT" ]; then
  emit > "$OUT"
else
  emit
fi
